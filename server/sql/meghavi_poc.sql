-- ---------------------------------------------------------------------------
-- Meghavi Wellness POC — PostgreSQL Schema
--
-- Three inference modules: Walk-ins, Meet & Greet, Reception Staff Availability
--
-- Apply:
--   psql -U aiserver -h 127.0.0.1 -p 5435 -d aiserver -f server/sql/meghavi_poc.sql
--
-- Safe to re-run (IF NOT EXISTS throughout).
-- Does NOT modify any existing ANPR or project tables.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- Locations — Woxsen & Woxsen
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meghavi_locations (
  id         SERIAL       PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  city       VARCHAR(100) NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Cameras — one row per physical camera used in the POC
-- camera_key  : the identifier the AI inference module sends (e.g. "cam-gachi-01")
-- location_id : resolved FK — the backend uses this, not the AI module
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meghavi_cameras (
  id           SERIAL       PRIMARY KEY,
  camera_key   VARCHAR(100) NOT NULL UNIQUE,
  location_id  INTEGER      NOT NULL REFERENCES meghavi_locations(id) ON DELETE RESTRICT,
  display_name VARCHAR(200) NULL,
  area         VARCHAR(100) NULL,   -- "Reception", "Waiting Lounge", etc.
  status       VARCHAR(20)  NOT NULL DEFAULT 'active',
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_meghavi_cameras_location ON meghavi_cameras(location_id);

-- ---------------------------------------------------------------------------
-- Module enable / config per camera
-- module: 'walkin' | 'meet_greet' | 'staff_availability'
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meghavi_camera_modules (
  id          SERIAL      PRIMARY KEY,
  camera_id   INTEGER     NOT NULL REFERENCES meghavi_cameras(id) ON DELETE CASCADE,
  module      VARCHAR(50) NOT NULL,
  enabled     BOOLEAN     NOT NULL DEFAULT true,
  settings    JSONB       NOT NULL DEFAULT '{}',
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (camera_id, module)
);

-- ---------------------------------------------------------------------------
-- Walk-in events — one row per detected customer entry
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meghavi_walkin_events (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id    INTEGER      NOT NULL REFERENCES meghavi_cameras(id) ON DELETE RESTRICT,
  detected_at  TIMESTAMPTZ  NOT NULL,
  person_count INTEGER      NOT NULL DEFAULT 1,
  confidence   NUMERIC(5,4) NULL,
  snapshot_url TEXT         NULL,
  video_url    TEXT         NULL,
  metadata     JSONB        NOT NULL DEFAULT '{}'
);
ALTER TABLE meghavi_walkin_events ADD COLUMN IF NOT EXISTS video_url TEXT NULL;
CREATE INDEX IF NOT EXISTS idx_mwe_detected   ON meghavi_walkin_events(detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_mwe_camera     ON meghavi_walkin_events(camera_id);
CREATE INDEX IF NOT EXISTS idx_mwe_cam_ts     ON meghavi_walkin_events(camera_id, detected_at DESC);

-- ---------------------------------------------------------------------------
-- Meet & Greet events — one row per customer arrival at reception
-- greeted               : true if a staff member attended within the window
-- greet_delay_seconds   : NULL means never greeted within the observation window
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meghavi_meet_greet_events (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id           INTEGER      NOT NULL REFERENCES meghavi_cameras(id) ON DELETE RESTRICT,
  detected_at         TIMESTAMPTZ  NOT NULL,
  greeted             BOOLEAN      NOT NULL,
  greet_delay_seconds INTEGER      NULL,
  confidence          NUMERIC(5,4) NULL,
  snapshot_url        TEXT         NULL,
  video_url           TEXT         NULL,
  metadata            JSONB        NOT NULL DEFAULT '{}'
);
ALTER TABLE meghavi_meet_greet_events ADD COLUMN IF NOT EXISTS video_url TEXT NULL;
CREATE INDEX IF NOT EXISTS idx_mmge_detected  ON meghavi_meet_greet_events(detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_mmge_camera    ON meghavi_meet_greet_events(camera_id);
CREATE INDEX IF NOT EXISTS idx_mmge_greeted   ON meghavi_meet_greet_events(greeted);
CREATE INDEX IF NOT EXISTS idx_mmge_cam_ts    ON meghavi_meet_greet_events(camera_id, detected_at DESC);

-- ---------------------------------------------------------------------------
-- Staff availability events — one row per detected absence window
-- staff_present           : false means reception desk was unattended
-- absent_duration_seconds : cumulative absence duration (only when staff_present=false)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meghavi_staff_availability_events (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id               INTEGER      NOT NULL REFERENCES meghavi_cameras(id) ON DELETE RESTRICT,
  detected_at             TIMESTAMPTZ  NOT NULL,
  staff_present           BOOLEAN      NOT NULL,
  absent_duration_seconds INTEGER      NULL,
  confidence              NUMERIC(5,4) NULL,
  snapshot_url            TEXT         NULL,
  video_url               TEXT         NULL,
  metadata                JSONB        NOT NULL DEFAULT '{}'
);
ALTER TABLE meghavi_staff_availability_events ADD COLUMN IF NOT EXISTS video_url TEXT NULL;
CREATE INDEX IF NOT EXISTS idx_msae_detected  ON meghavi_staff_availability_events(detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_msae_camera    ON meghavi_staff_availability_events(camera_id);
CREATE INDEX IF NOT EXISTS idx_msae_present   ON meghavi_staff_availability_events(staff_present);
CREATE INDEX IF NOT EXISTS idx_msae_cam_ts    ON meghavi_staff_availability_events(camera_id, detected_at DESC);

